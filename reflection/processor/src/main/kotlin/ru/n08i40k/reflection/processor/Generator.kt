package ru.n08i40k.reflection.processor

import java.util.TreeSet

private const val REFLECTION_PACKAGE = "ru.n08i40k.reflection"

private class Argument(
    val expression: String,
    val comment: String? = null
)

internal fun generateFile(
    packageName: String,
    classes: List<RuntimeClass>,
    owners: List<Owner>,
    optIn: Boolean
): String =
    FileGenerator(optIn)
        .generate(packageName, classes, owners)

private class FileGenerator(
    private val optIn: Boolean
) {
    private val imports = TreeSet<String>()
    private val optInMarkers = TreeSet<String>()
    private val body = StringBuilder()

    fun generate(packageName: String, classes: List<RuntimeClass>, owners: List<Owner>): String {
        // классы объявляются первыми: свойства файла инициализируются по порядку, а члены на них ссылаются
        for (runtimeClass in classes)
            emitClass(runtimeClass)

        for (owner in owners) {
            val ownerDoc = owner.declaration.docString

            owner.members.forEachIndexed { index, member ->
                val docs = listOfNotNull(
                    if (index == 0)
                        ownerDoc
                    else
                        null,
                    member.doc
                )

                emitMember(owner, member, docs)
            }
        }

        return buildString {
            append("// Generated by reflection-processor. Do not edit.\n")
            append("@file:Suppress(\"ObjectPropertyName\", \"RedundantVisibilityModifier\", \"RemoveRedundantQualifierName\")\n")

            if (optInMarkers.isNotEmpty()) {
                append("@file:OptIn(")
                append(optInMarkers.joinToString(", ") { "$it::class" })
                append(")\n")
            }

            append('\n')
            append("package ")
            append(packageName)
            append("\n\n")

            for (import in imports) {
                append("import ")
                append(import)
                append('\n')
            }

            if (imports.isNotEmpty())
                append('\n')

            append(body.trimEnd())
            append('\n')
        }
    }

    private fun reflection(function: String): String {
        imports.add("$REFLECTION_PACKAGE.$function")
        return function
    }

    private fun emitProperty(
        docs: List<String>,
        availability: Availability,
        public: Boolean,
        name: String,
        type: String,
        expression: String,
    ) = with(body) {
        val lines = docs
            .flatMap { it.trim().lines() }
            .map { it.trim() }

        if (lines.isNotEmpty()) {
            append("/**\n")

            for (line in lines) {
                append(
                    if (line.isEmpty())
                        " *\n"
                    else
                        " * $line\n"
                )
            }

            append(" */\n")
        }

        if (optIn) {
            optInAnnotation(availability)
                ?.let {
                    append(it)
                    append('\n')
                }
        }

        append("@JvmField\n")

        append(
            if (public)
                "public"
            else
                "internal"
        )
        append(" val `")
        append(name)

        append("`: ")
        append(type)
        append(" =\n")

        append("    ")
        append(expression)
        append("\n\n")
    }

    private fun optInAnnotation(availability: Availability): String? = with(availability) {
        val (marker, arguments) = when {
            since != null && before != null -> "RequiresClientBetween" to "\"$since\", \"$before\""
            since != null -> "RequiresClientSince" to "\"$since\""
            before != null -> "RequiresClientBefore" to "\"$before\""
            else -> return null
        }

        imports.add("$REFLECTION_PACKAGE.$marker")
        optInMarkers.add(marker)

        return "@$marker($arguments)"
    }

    private fun emitClass(runtimeClass: RuntimeClass) {
        val literal = kotlinString(runtimeClass.binaryName)

        if (runtimeClass.availability.nullable)
            emitProperty(
                emptyList(),
                runtimeClass.availability,
                runtimeClass.public,
                runtimeClass.propertyName,
                "Class<*>?",
                "${reflection("getClassIfExists")}($literal)",
            )
        else
            emitProperty(
                emptyList(),
                runtimeClass.availability,
                runtimeClass.public,
                runtimeClass.propertyName,
                "Class<*>",
                "Class.forName($literal)",
            )
    }

    private fun emitMember(owner: Owner, member: Member, docs: List<String>) {
        val nullable = member.availability.nullable

        val ifExists =
            if (nullable)
                "IfExists"
            else
                ""

        when (member) {
            is FieldsMember -> {
                imports.add("$REFLECTION_PACKAGE.ClonableFields")

                emitProperty(
                    docs,
                    member.availability,
                    owner.public,
                    member.propertyName,
                    "ClonableFields",
                    "${reflection("getAccessibleFields")}(${owner.expression})",
                )

                return
            }

            is FieldMember -> {
                val function = buildString {
                    append("getField")
                    append(
                        if (member.access == FieldAccess.GET)
                            "Getter"
                        else
                            "Setter"
                    )
                    append(ifExists)
                }

                val call = call(
                    reflection(function),
                    listOf(Argument(owner.expression), Argument(kotlinString(member.name)))
                )

                emitHandle(docs, owner, member, call + retype(member.retype, nullable))
            }

            is MethodMember -> {
                val parameters = member.parameters
                    .map { Argument(it.type.expression, it.name) }

                val call = if (member.isConstructor) {
                    call(
                        reflection("getConstructorHandle$ifExists"),
                        listOf(Argument(owner.expression)) + parameters
                    )
                } else {
                    call(
                        reflection("getMethodHandle$ifExists"),
                        listOf(
                            Argument(owner.expression),
                            Argument(kotlinString(member.name))
                        ) + parameters,
                    )
                }

                emitHandle(docs, owner, member, call + retype(member.retype, nullable))
            }
        }
    }

    private fun emitHandle(docs: List<String>, owner: Owner, member: Member, expression: String) {
        imports.add("java.lang.invoke.MethodHandle")

        emitProperty(
            docs,
            member.availability,
            owner.public,
            member.propertyName,
            if (member.availability.nullable)
                "MethodHandle?"
            else
                "MethodHandle",
            expression,
        )
    }

    private fun retype(types: List<TypeRef>?, nullable: Boolean): String {
        if (types == null)
            return ""

        return buildString {
            append("\n        ")

            append(
                if (nullable)
                    "?."
                else
                    "."
            )

            append(reflection("retype"))

            append("(")
            append(types.joinToString(", ") { it.expression })
            append(")")
        }
    }

    private fun call(function: String, arguments: List<Argument>): String {
        val single = "$function(${arguments.joinToString(", ") { it.expression }})"

        if (arguments.none { it.comment != null } && single.length <= 100)
            return single

        return buildString {
            append(function)
            append("(\n")

            for (argument in arguments) {
                append("        ")
                append(argument.expression)
                append(',')

                argument.comment
                    ?.let {
                        append(" // ")
                        append(it)
                    }

                append('\n')
            }

            append("    )")
        }
    }

    private fun kotlinString(value: String): String =
        buildString {
            append("\"")
            append(
                value
                    .replace("\\", "\\\\")
                    .replace("\"", "\\\"")
                    .replace("$", "\\$")
            )
            append("\"")
        }
}
